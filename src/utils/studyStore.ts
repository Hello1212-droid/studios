/** DashboardStats — Computed analytics for the scheduler dashboard. */
export interface DashboardStats {
  totalTasks: number;
  completedTasks: number;
  completionRate: number;             // 0-100 percentage
  totalStudyMinutes: number;
  totalBreakMinutes: number;
  breakCount: number;
  subjectBreakdown: {                 // Per-subject analytics
    subject: string;
    totalMinutes: number;
    completedMinutes: number;
    tasksCount: number;
    completedTasks: number;
  }[];
  todayAuditLog: AuditEntry[];        // Today's audit trail entries
}

/**
 * calculateDashboardStats(tasks, auditLog)
 * Computes today's study statistics from tasks and audit trail.
 * Used by the Scheduler's dashboard panel.
 */
export const calculateDashboardStats = (
  tasks: SubjectTask[],
  auditLog: AuditEntry[]
): DashboardStats => {
  const today = new Date().toISOString().split('T')[0];
  const todayTasks = tasks.filter(t => t.date === today);
  const todayAuditLog = auditLog.filter(e => e.timestamp.startsWith(today));

  const totalTasks = todayTasks.length;
  const completedTasks = todayTasks.filter(t => t.completed).length;
  const completionRate = totalTasks > 0
    ? Math.round((completedTasks / totalTasks) * 100)
    : 0;

  const totalStudyMinutes = todayTasks.reduce((acc, t) => acc + t.duration, 0);

  // Extract break stats from audit log
  const breakStarts = todayAuditLog.filter(e => e.action === 'START_BREAK');
  const breakEnds = todayAuditLog.filter(e => e.action === 'STOP_BREAK');
  const breakCount = breakStarts.length;

  let totalBreakMinutes = 0;
  breakEnds.forEach(e => {
    if (e.metadata?.durationSeconds) {
      totalBreakMinutes += Math.ceil(e.metadata.durationSeconds / 60);
    }
  });

  // Per-subject breakdown
  const subjectMap = new Map<string, {
    totalMin: number;
    completedMin: number;
    tasksCount: number;
    completedTasks: number;
  }>();

  todayTasks.forEach(t => {
    const key = t.subjectDisplay || t.subject;
    const existing = subjectMap.get(key) || {
      totalMin: 0, completedMin: 0, tasksCount: 0, completedTasks: 0
    };
    existing.totalMin += t.duration;
    existing.tasksCount += 1;
    if (t.completed) {
      existing.completedMin += t.duration;
      existing.completedTasks += 1;
    }
    subjectMap.set(key, existing);
  });

  const subjectBreakdown = Array.from(subjectMap.entries()).map(([subject, data]) => ({
    subject,
    totalMinutes: data.totalMin,
    completedMinutes: data.completedMin,
    tasksCount: data.tasksCount,
    completedTasks: data.completedTasks
  }));

  return {
    totalTasks,
    completedTasks,
    completionRate,
    totalStudyMinutes,
    totalBreakMinutes,
    breakCount,
    subjectBreakdown,
    todayAuditLog
  };
};

