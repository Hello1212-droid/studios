/** ScheduleResult — Output of the schedule generation algorithm. */
export interface ScheduleResult {
  tasks: SubjectTask[];                          // Generated study blocks
  totalMinutes: number;                          // Total study time in minutes
  subjectAllocations: {                          // Per-subject breakdown
    subject: string;
    minutes: number;
    percentage: number;
  }[];
}

/**
 * generateDynamicSchedule()
 * ─────────────────────────────────────────────────────────────────
 * THE FORGE PROTOCOL — The core scheduling algorithm.
 *
 * Inputs:
 *   subjects        → Array of {name, priority}
 *   startTimeStr    → "8:00 PM"
 *   endTimeStr      → "1:30 AM"
 *   breakInterval   → Study for X minutes, then break (default: 50)
 *   breakDuration   → Break for Y minutes (default: 10)
 *
 * Algorithm:
 *   1. Calculate totalAvailable minutes (handles cross-midnight)
 *   2. Distribute minutes across subjects proportionally to priority
 *   3. Sort subjects by priority (high priority first)
 *   4. Round-robin: allocate blocks for each subject until time runs out
 *   5. Insert breaks every breakInterval minutes
 *   6. Skip subjects that have received their full allocation
 *   7. Safety: maxIterations prevents infinite loops
 *
 * Priority weighting:
 *   totalWeight = sum of all subject priorities
 *   subjectAllocation = (subject.priority / totalWeight) * totalAvailable
 *   P3 subjects get ~50% more time than P2, ~3x more than P1
 */
export const generateDynamicSchedule = (
  subjects: SubjectConfig[],
  startTimeStr: string,
  endTimeStr: string,
  breakInterval: number = 50,    // Study for 50 min before break
  breakDuration: number = 10      // Break for 10 min
): ScheduleResult => {
  let currentMinutes = parseTime12toMinutes(startTimeStr);    // Start in minutes
  let endMinutes = parseTime12toMinutes(endTimeStr);          // End in minutes

  // Handle cross-midnight study sessions (e.g., 8:00 PM → 1:30 AM)
  if (endMinutes <= currentMinutes) {
    endMinutes += 24 * 60; // Add 24 hours to end time
  }

  const totalAvailable = endMinutes - currentMinutes;          // Total study window

  // Guard: no time available or no subjects configured
  if (totalAvailable <= 0 || subjects.length === 0) {
    return { tasks: [], totalMinutes: 0, subjectAllocations: [] };
  }

  const tasks: SubjectTask[] = [];
  const totalWeight = subjects.reduce((acc, s) => acc + s.priority, 0);

  // Sort by priority descending (P3 first, then P2, then P1)
  const sortedSubjects = [...subjects].sort((a, b) => b.priority - a.priority);

  // Calculate proportional allocations
  const allocations: { name: string; priority: number; allocated: number }[] =
    sortedSubjects.map(s => ({
      name: s.name,
      priority: s.priority,
      allocated: (s.priority / totalWeight) * totalAvailable
    }));

  // Build the allocation summary for the preview UI
  const subjectAllocations = allocations.map(a => ({
    subject: a.name,
    minutes: Math.round(a.allocated),
    percentage: Math.round((a.allocated / totalAvailable) * 100)
  }));

  let timeSinceLastBreak = 0;          // Minutes since last break insertion
  const today = new Date().toISOString().split('T')[0]; // "2026-07-24"
  let subjectIndex = 0;                // Current subject being allocated
  const maxIterations = 1000;          // Safety: prevent infinite loops
  let iterations = 0;

  // Main allocation loop
  while (currentMinutes < endMinutes && subjectIndex < sortedSubjects.length && iterations < maxIterations) {
    iterations++;

    // ── BREAK CHECK ────────────────────────────────────────────
    // If we've studied for breakInterval minutes, insert a break
    if (timeSinceLastBreak >= breakInterval) {
      const breakEnd = Math.min(currentMinutes + breakDuration, endMinutes);
      currentMinutes = breakEnd;        // Skip ahead past the break
      timeSinceLastBreak = 0;          // Reset break counter
      continue;                         // Re-evaluate from the top
    }

    const sub = allocations[subjectIndex];
    if (!sub) break; // Safety: shouldn't happen

    // How many minutes have we already allocated to this subject?
    const alreadyAllocated = tasks
      .filter(t => t.subject === sub.name)
      .reduce((acc, t) => acc + t.duration, 0);

    const remainingForSubject = sub.allocated - alreadyAllocated;

    // If this subject has received its full allocation, move to the next
    if (remainingForSubject <= 0) {
      subjectIndex++;
      continue;
    }

    // Calculate the actual block duration:
    //   Min of: remaining for subject, remaining total time, time until next break
    const remainingTime = endMinutes - currentMinutes;
    const availableBeforeBreak = breakInterval - timeSinceLastBreak;
    const duration = Math.min(remainingForSubject, remainingTime, availableBeforeBreak);

    // Skip blocks smaller than 10 minutes (too short to be meaningful)
    if (duration < 10) {
      subjectIndex++;
      continue;
    }

    // Commit the block
    const blockStartMinutes = currentMinutes;
    currentMinutes += duration;
    timeSinceLastBreak += duration;

    tasks.push({
      id: Math.random().toString(36).substr(2, 9),    // Random alphanumeric ID
      subject: sub.name,
      subjectDisplay: sub.name,
      type: 'STUDY',
      title: `${sub.name} Focused Study`,
      subtitle: `Deep work on ${sub.name}`,
      duration: Math.floor(duration),
      startTime: formatMinutesTo12(blockStartMinutes),
      endTime: formatMinutesTo12(currentMinutes),
      completed: false,
      date: today,
      isDebt: false,
      priority: sub.priority
    });
  }

  return { tasks, totalMinutes: totalAvailable, subjectAllocations };
};

// ═══════════════════════════════════════════════════════════════
// REBALANCE AFTER BREAK
// ═══════════════════════════════════════════════════════════════

/**
 * rebalanceSchedule()
 * Recalculates the remaining schedule after a break or task completion.
 * Takes remaining incomplete tasks and regenerates from current time.
 */
export const rebalanceSchedule = (
  currentTasks: SubjectTask[],
  completedTaskIds: string[],
  currentTimeStr: string,
  endTimeStr: string,
  breakInterval: number = 50,
  breakDuration: number = 10
): ScheduleResult => {
  // Filter out completed tasks
  const remainingTasks = currentTasks.filter(t => !completedTaskIds.includes(t.id));

  // Extract unique subjects with their priorities from remaining tasks
  const subjectPriorityMap = new Map<string, number>();
  remainingTasks.forEach(t => {
    const existing = subjectPriorityMap.get(t.subject);
    if (!existing || t.priority > existing) {
      subjectPriorityMap.set(t.subject, t.priority);
    }
  });

  // Check if endTime has already passed
  const currentMinutes = parseTime12toMinutes(currentTimeStr);
  let endMinutes = parseTime12toMinutes(endTimeStr);
  if (endMinutes <= currentMinutes) {
    endMinutes += 24 * 60;
  }

  // Nothing left to schedule
  if (currentMinutes >= endMinutes || subjectPriorityMap.size === 0) {
    return { tasks: [], totalMinutes: 0, subjectAllocations: [] };
  }

  const subjects: SubjectConfig[] = Array.from(subjectPriorityMap.entries()).map(
    ([name, priority]) => ({ name, priority })
  );

  // Regenerate from current time with remaining subjects
  return generateDynamicSchedule(subjects, currentTimeStr, endTimeStr, breakInterval, breakDuration);
};

