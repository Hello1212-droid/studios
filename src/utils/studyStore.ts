/**
 * processNeelaAction(state, aiResponse)
 * Parses [ACTION]...[\/ACTION] blocks from Neela's AI response.
 * Neela can issue structured commands that modify the app state:
 *
 *   ADD_TASKS: Create new study tasks in the scheduler
 *     Example: { "type": "ADD_TASKS", "payload": [{ "subject": "PHYSICS", ... }] }
 *
 *   UPDATE_PCM: Update PCM chapter health data
 *     Example: { "type": "UPDATE_PCM", "payload": { "subject": "PHYSICS", ... } }
 *
 * This is the core of Neela's "agentic" capability — she's not just
 * a chatbot, she can directly modify the user's study plan.
 */
export const processNeelaAction = (state: StudyState, aiResponse: string): StudyState => {
  try {
    // Extract [ACTION] block from the AI response
    const actionMatch = aiResponse.match(/\[ACTION\]([\s\S]*?)\[\/ACTION\]/);
    if (!actionMatch) return state; // No action block found

    const action = JSON.parse(actionMatch[1]); // Parse the JSON payload
    let newState = { ...state };

    // ── ADD_TASKS: Create new study blocks ──────────────────
    if (action.type === 'ADD_TASKS') {
      const today = new Date().toISOString().split('T')[0];
      const newTasks = action.payload.map((t: any) => ({
        id: Math.random().toString(36).substr(2, 9),
        completed: false,
        isDebt: false,
        date: today,
        ...t  // Spread the rest (subject, type, title, duration, startTime, endTime)
      }));
      newState.tasks = [...newState.tasks, ...newTasks];
      newState = logAction(newState, 'NEELA_ADD_TASKS', 'AI generated schedule update');
    }

    // ── UPDATE_PCM: Update chapter health ───────────────────
    if (action.type === 'UPDATE_PCM') {
      const { subject, chapter, dpp, backlog } = action.payload;
      const sub = subject.toLowerCase();
      const chapterIdx = newState.pcm[sub]?.findIndex(
        (c: any) => c.name.toLowerCase() === chapter.toLowerCase()
      );
      if (chapterIdx !== undefined && chapterIdx > -1) {
        if (dpp) newState.pcm[sub][chapterIdx].dpps.push(dpp);
        if (backlog) newState.pcm[sub][chapterIdx].backlogs.push(backlog);
      }
    }

    return newState;
  } catch (e) {
    // If parsing fails, return state unchanged (graceful degradation)
    return state;
  }
};
