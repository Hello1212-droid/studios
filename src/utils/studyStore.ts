const STORAGE_KEY = 'studyos_data_v3';   // localStorage key

/** createDefaultState() — Returns a fresh StudyState with sensible defaults. */
const createDefaultState = (): StudyState => ({
  tasks: [],
  auditLog: [],
  testResults: [],
  chatHistory: [],
  pcm: {
    physics:   [{ name: 'Rotation',        dpps: [], backlogs: [] }],
    chemistry: [{ name: 'Thermodynamics',   dpps: [], backlogs: [] }],
    maths:     [{ name: 'Integration',      dpps: [], backlogs: [] }],
  },
  lastLogin: new Date().toISOString().split('T')[0],
  session: {
    isActive: false, isBreak: false,
    currentTaskId: null, currentTaskIndex: -1,
    studyStartedAt: null, breakStartedAt: null,
    totalStudySeconds: 0, totalBreakSeconds: 0,
    breakCount: 0, completedTaskIds: []
  },
  config: {
    startTime: "18:00", endTime: "23:00",
    breakInterval: 50, breakDuration: 10
  }
});

/** loadState() — Reads StudyState from localStorage, or returns a fresh default. */
export const loadState = (): StudyState => {
  const saved = localStorage.getItem(STORAGE_KEY);
  try {
    if (saved) {
      const parsed = JSON.parse(saved);
      // Migrate: ensure session field exists for legacy data
      if (!parsed.session) {
        parsed.session = createDefaultState().session;
      }
      return parsed as StudyState;
    }
  } catch (e) {
    // Corrupted data → start fresh (graceful degradation)
  }
  return createDefaultState();
};

/** saveState(state) — Persists the entire StudyState to localStorage. */
export const saveState = (state: StudyState) => {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(state));
  } catch (e) {
    console.error('[StudyOS] Failed to save state:', e);
  }
};

