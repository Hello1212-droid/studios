/** TaskType — Classification for each study task in the scheduler. */
export type TaskType = 'DPP' | 'HOMEWORK' | 'BACKLOG' | 'SURGERY' | 'STUDY';

/** Subject — A subject name string (e.g., "PHYSICS", "CHEMISTRY", "MATHS"). */
export type Subject = string;

/** STANDARD_SUBJECTS — The core PCM subjects for JEE preparation. */
export const STANDARD_SUBJECTS = ['PHYSICS', 'CHEMISTRY', 'MATHS'] as const;

/**
 * SubjectConfig — User-defined subject for schedule generation.
 *   name     → "PHYSICS", "CHEMISTRY", etc.
 *   priority → 1 (low) to 3 (high). Higher priority = more time allocated.
 */
export interface SubjectConfig {
  name: string;
  priority: number;
}

/**
 * TestResult — A single mock test entry logged by the user.
 * Used by TestResultEngine to predict JEE 2027 score.
 */
export interface TestResult {
  id: string;                       // Unique ID
  date: string;                     // "2026-07-24"
  testName: string;                 // e.g., "AITS Phase 1"
  provider: string;                 // "FIITJEE", "ALLEN", etc.
  score: number;                    // Marks obtained
  total: number;                    // Total marks possible
  rank: number;                     // User's rank in the test
  totalStudents: number;            // Total candidates in the test
  overallPercentile: number;        // Mock percentile from rank
  subjectPercentiles: Record<Subject, number>; // Per-subject percentiles
  jeeEquivalentPercentile: number;   // Scaled to JEE 2027 equivalent
  targetPercentile: number;          // Next milestone target
}

/** ChatMessage — A single message in the Neela chat history. */
export interface ChatMessage {
  role: 'user' | 'assistant';       // Who sent the message
  content: string;                  // Markdown-formatted message body
  timestamp: string;                // ISO timestamp
}

/** ChatSession — A full conversation with Neela. Multiple sessions are saved. */
export interface ChatSession {
  id: string;                       // Unique session ID
  timestamp: string;                // Session creation time
  title: string;                    // Session title (first user message)
  messages: ChatMessage[];          // Ordered message history
}

/**
 * SubjectTask — A single study block in the schedule.
 * Generated by the Forge Protocol algorithm.
 */
export interface SubjectTask {
  id: string;                       // Unique task ID
  subject: Subject;                 // e.g., "PHYSICS"
  subjectDisplay?: string;          // Display name (may differ from subject)
  type: TaskType;                   // Task classification
  title: string;                    // e.g., "PHYSICS Focused Study"
  subtitle: string;                 // e.g., "Deep work on PHYSICS"
  duration: number;                 // Duration in minutes
  startTime: string;                // "8:00 PM" (12h format)
  endTime: string;                  // "9:15 PM" (12h format)
  completed: boolean;               // Has the user marked this done?
  date: string;                     // "2026-07-24"
  isDebt: boolean;                  // Carried over from a previous day?
  priority: number;                 // 1-3 priority level
}

/** AuditEntry — A single event in the audit trail. */
export interface AuditEntry {
  timestamp: string;                // ISO timestamp
  action: string;                   // e.g., "START_STUDY", "COMPLETE_TASK"
  reason?: string;                  // Optional description
  metadata?: any;                   // Extra data (task ID, duration, etc.)
}

/** StudySessionState — Current study session runtime state. */
export interface StudySessionState {
  isActive: boolean;                // Is a study timer running?
  isBreak: boolean;                 // Is a break timer running?
  currentTaskId: string | null;     // Which task is being worked on
  currentTaskIndex: number;         // Index in the task list
  studyStartedAt: number | null;    // Date.now() when study started
  breakStartedAt: number | null;    // Date.now() when break started
  totalStudySeconds: number;        // Accumulated study time this session
  totalBreakSeconds: number;        // Accumulated break time this session
  breakCount: number;               // How many breaks taken
  completedTaskIds: string[];       // IDs of completed tasks
}

/**
 * StudyState — THE SINGLE SOURCE OF TRUTH.
 * This entire object is serialized to localStorage.
 */
export interface StudyState {
  tasks: SubjectTask[];             // All study tasks (today + debt)
  auditLog: AuditEntry[];           // Full audit trail (last 100 entries)
  testResults: TestResult[];        // Mock test history (newest first)
  chatHistory: ChatSession[];       // Neela conversation history
  pcm: any;                         // PCM chapter health data (legacy)
  lastLogin: string;                // Date of last login ("2026-07-24")
  session: StudySessionState;       // Current study session state
  config: {                         // User configuration
    startTime: string;              // "18:00" (24h)
    endTime: string;                // "23:00" (24h)
    breakInterval: number;          // Minutes between breaks
    breakDuration: number;          // Break length in minutes
  };
}

