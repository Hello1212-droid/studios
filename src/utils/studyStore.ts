/**
 * updateChatSession(state, session)
 * Upserts a chat session into the chatHistory array.
 * If the session already exists (by ID), updates it.
 * If new, prepends it (newest first).
 * Auto-saves to localStorage.
 */
export const updateChatSession = (state: StudyState, session: ChatSession): StudyState => {
  const existingIdx = state.chatHistory.findIndex(s => s.id === session.id);
  let newHistory = [...state.chatHistory];
  if (existingIdx >= 0) {
    newHistory[existingIdx] = session;  // Update existing
  } else {
    newHistory = [session, ...newHistory]; // Prepend new
  }
  const newState = { ...state, chatHistory: newHistory };
  saveState(newState);
  return newState;
};

/**
 * calculateCarryForward(tasks)
 * Converts incomplete past tasks into "debt" tasks.
 * Called once per day on app mount (when lastLogin !== today).
 * Tasks with isDebt: true appear with high priority in the scheduler.
 */
export const calculateCarryForward = (tasks: SubjectTask[]): SubjectTask[] => {
  const today = new Date().toISOString().split('T')[0];
  return tasks.map(task => {
    if (!task.completed && task.date < today && !task.isDebt) {
      return { ...task, isDebt: true };
    }
    return task;
  });
};

/**
 * logAction(state, action, reason?, metadata?)
 * Appends an audit entry to the audit log.
 * Keeps only the last 100 entries (prevents unbounded growth).
 * Auto-saves to localStorage.
 */
export const logAction = (
  state: StudyState,
  action: string,
  reason?: string,
  metadata?: any
): StudyState => {
  const entry: AuditEntry = {
    timestamp: new Date().toISOString(),
    action,
    reason,
    metadata
  };
  // Keep only the last 100 entries + the new one
  const newState = {
    ...state,
    auditLog: [...state.auditLog.slice(-99), entry]
  };
  saveState(newState);
  return newState;
};

