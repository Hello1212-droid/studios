/**
 * parseTime12toMinutes(timeStr)
 * Converts 12h time string → minutes from midnight.
 * "8:00 PM"  → 1200 (20 * 60)
 * "01:30 AM" → 90   (1.5 * 60)
 */
export const parseTime12toMinutes = (timeStr: string): number => {
  const match12 = timeStr.match(/(\d{1,2}):(\d{2})\s*(AM|PM)/i);
  if (match12) {
    let hours = parseInt(match12[1]);
    const minutes = parseInt(match12[2]);
    const ampm = match12[3].toUpperCase();
    // Adjust for 12h clock: 12 PM = 12, 12 AM = 0
    if (ampm === 'PM' && hours !== 12) hours += 12;
    if (ampm === 'AM' && hours === 12) hours = 0;
    return hours * 60 + minutes;
  }
  // Fallback: try 24h format ("18:00")
  const [h, m] = timeStr.split(':').map(Number);
  return h * 60 + (m || 0);
};

/**
 * formatMinutesTo12(minutes)
 * Converts minutes from midnight → 12h time string.
 * Example: 1200 → "8:00 PM", 90 → "1:30 AM"
 */
export const formatMinutesTo12 = (minutes: number): string => {
  // Normalize to 0-1439 range (handle cross-midnight values)
  const totalMinutes = ((minutes % 1440) + 1440) % 1440;
  const h = Math.floor(totalMinutes / 60);
  const min = totalMinutes % 60;
  const ampm = h >= 12 ? 'PM' : 'AM';
  const h12 = h % 12 || 12; // Convert 0 → 12 for 12 AM
  return `${h12}:${String(min).padStart(2, '0')} ${ampm}`;
};

/** getCurrentTimeMinutes() — Returns current time as minutes from midnight. */
export const getCurrentTimeMinutes = (): number => {
  const now = new Date();
  return now.getHours() * 60 + now.getMinutes();
};

